"""Generate deterministic PyInstaller version resources from product identity."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from light_image_editor.identity import (
    COPYRIGHT,
    DESCRIPTION,
    EXECUTABLE_NAME,
    INTERNAL_NAME,
    PRODUCT_NAME_EN,
    PRODUCT_NAME_ZH,
    PUBLISHER,
    VERSION,
)

_NUMERIC_VERSION = re.compile(r"^(?P<numbers>\d+(?:\.\d+){0,3})(?:[-+].*)?$")


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """Convert a PEP 440-like release version to a Windows four-part version."""

    match = _NUMERIC_VERSION.fullmatch(version)
    if match is None:
        raise ValueError(f"Windows file versions need one to four numeric parts: {version!r}")
    parts = [int(part) for part in match.group("numbers").split(".")]
    if any(part > 65535 for part in parts):
        raise ValueError(f"Windows file version components must be <= 65535: {version!r}")
    padded = (parts + [0, 0, 0, 0])[:4]
    return padded[0], padded[1], padded[2], padded[3]


def _pyinstaller_string(value: str) -> str:
    return repr(value)


def render_version_info(kind: str = "app") -> str:
    """Render a PyInstaller ``--version-file`` document."""

    if kind not in {"app", "installer"}:
        raise ValueError(f"Unknown binary kind: {kind!r}")

    numeric_version = version_tuple(VERSION)
    original_filename = EXECUTABLE_NAME if kind == "app" else "ImageEditorSetup.exe"
    internal_name = INTERNAL_NAME if kind == "app" else f"{INTERNAL_NAME}Setup"
    description = DESCRIPTION if kind == "app" else f"{PRODUCT_NAME_ZH}安装程序"
    product_name = f"{PRODUCT_NAME_ZH} ({PRODUCT_NAME_EN})"

    strings = {
        "CompanyName": PUBLISHER,
        "FileDescription": description,
        "FileVersion": VERSION,
        "InternalName": internal_name,
        "LegalCopyright": COPYRIGHT,
        "OriginalFilename": original_filename,
        "ProductName": product_name,
        "ProductVersion": VERSION,
    }
    string_rows = "\n".join(
        f"        StringStruct({_pyinstaller_string(key)}, {_pyinstaller_string(value)}),"
        for key, value in strings.items()
    )
    version_literal = ", ".join(str(part) for part in numeric_version)

    return f"""# Generated by scripts/generate_version_info.py; do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({version_literal}),
    prodvers=({version_literal}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '080404B0',
        [
{string_rows}
        ],
      ),
    ]),
    VarFileInfo([VarStruct('Translation', [2052, 1200])]),
  ],
)
"""


def write_version_info(output: Path, kind: str = "app") -> None:
    """Write version metadata only when content changed."""

    content = render_version_info(kind)
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text(encoding="utf-8") == content:
        return
    output.write_text(content, encoding="utf-8", newline="\n")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--kind", choices=("app", "installer"), default="app")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    write_version_info(args.output, args.kind)


if __name__ == "__main__":
    main()
